        var result = text
        for ((pattern, arWord, enWord) in ASCII_EMOTICONS) {
            result = pattern.matcher(result).replaceAll(
                Matcher.quoteReplacement(if (arabic) arWord else enWord)
            )
        }
        return result
    }

