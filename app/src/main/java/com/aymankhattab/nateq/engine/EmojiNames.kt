    fun arName(cp: Int): String? = AR[cp]
    fun enName(cp: Int): String? = EN[cp]

    /** اسم الدولة للعلم (رمز من حرفين) في العربية أو الإنجليزية. */
    fun flagName(code: String, arabic: Boolean): String? =
        if (arabic) AR_COUNTRY[code] else EN_COUNTRY[code]

    /** رمز دولة (حرفان) من رمزي منطقة متجاورين (🇪🇬 → "EG"). */
    fun buildCountryCode(c1: Int, c2: Int): String {
        val a = (c1 - 0x1F1E6 + 'A'.code).toChar()
        val b = (c2 - 0x1F1E6 + 'A'.code).toChar()
        return "$a$b"
    }

    /** تمييز مؤشرات المناطق (🇦️..🇿️): تُقرن مثنىً لتكوين أعلام. */
    fun isRegionalIndicator(cp: Int): Boolean = cp in 0x1F1E6..0x1F1FF

    /** تعديلات إيموجي تُسقط بصمت: ZWJ، ألوان البشرة، مؤشرات شكل النص. */
    fun isEmojiModifier(cp: Int): Boolean =
        cp == 0x200D || cp in 0xFE0E..0xFE0F || cp in 0x1F3FB..0x1F3FF

    /** كتل الإيموجي الصوريّة (بدون مؤشر الشكل FE0F الذي يُعالج كتعديل). */
    fun isEmojiBlockCp(cp: Int): Boolean =
        cp in 0x1F300..0x1FAFF || cp in 0x2600..0x27BF ||
        cp in 0x2B00..0x2BFF || cp in 0x1F000..0x1F1FF

    /** اسم نطق العلم كاملاً («علم السعودية»/«flag of Saudi Arabia») مع تراجعٍ عام. */
    fun flagReadingName(code: String, arabic: Boolean): String {
        val country = flagName(code, arabic)
        return if (country != null) {
            (if (arabic) "علم " else "flag of ") + country
        } else if (arabic) {
            AR_FLAG_FALLBACK
        } else {
            EN_FLAG_FALLBACK
        }
    }

