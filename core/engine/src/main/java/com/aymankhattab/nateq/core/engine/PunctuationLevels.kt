package com.aymankhattab.nateq.core.engine

/**
 * مستويات نطق علامات الترقيم والرموز في النصوص.
 * 0 = لا شيء، 1 = البعض، 2 = الكل.
 */
object PunctuationLevels {

    /** لا شيء: لا تُنطق أسماء علامات الترقيم والرموز (تبقى وقفات طبيعية). */
    const val NONE = 0

    /** البعض: الرموز الأساسية الشائعة
     * (@ المعزولة، #، %، &، +، /، = المعزولة). */
    const val SOME = 1

    /** الكل: يضيف فوق «البعض» الأقواس والفواصل
     * المنقوطة والشرطات والنقاط. */
    const val ALL = 2

    /** أدنى/أقصى قيمة صالحة للمستوى. */
    const val MIN = NONE
    const val MAX = ALL
}