package com.aymankhattab.nateq.engine.pipeline

/**
 * تجريد التشكيل العربي من النص (حركات، تنوين، شدّة، سكون، تطويل/كشيدة،
 * والعلامات الإملائية الرافدة) دون لمس الحروف أو فواصل الكلمات.
 * ضروري قبل مطابقة الأنماط والقواميس: علامات Unicode الفاصلة عن الحرف
 * (Mn) تجعل [Character.isLetter] تعود false وتفكك تعبيرات regex العربية،
 * كما أن الكلمة المشكولة لا تُطابق مدخلات القاموس المكتوبة بلا تشكيل.
 * تُطبَّق على مدخل المعالجة فقط، وبالتالي لا تُحذف من نصٍّ ليس عربياً.
 *
 * **زخارف المصحف والرموز الخاصة:**
 * - U+0670 (ألف خنجرية علوية) تُحذف مع سائر الحركات — سبق أن حُفظت
 *   «للمصحف» لكن مدخلات القرآن الملصوقة تحوي أيضاً U+06DE (۞) و U+FDFD
 *   (﷽) التي تُشوّش النطق؛ القرار الشامل: جرد كل الزخارف الزائدة.
 * - U+06DE (۞ دائرة الآية) داخل نطاق U+06D6..U+06E4 المحذوف أصلاً.
 * - U+FDFD (﷽) وU+FDF2 وما يليها (أشكال عرض عربية مزخرفة) تُحذف.
 * - U+06AA (ڪ كاف مائلة شرقية) تُستبدل بـ ك (U+0643) الاعتيادية لا تُحذف.
 */
internal object TashkeelStripStep : TextProcessingStep {

    override fun apply(input: String): String {
        if (input.isEmpty()) return input
        val sb = StringBuilder(input.length)
        for (ch in input) {
            val cp = ch.code
            // نطاقات التشكيل العربي الكاملة (U+0610–U+061A، U+064B–U+065F)
            // بالإضافة للتطويل/الكشيدة (U+0640) والألف الخنجرية (U+0670).
            // علامات الضبط المصحفي (U+06D6–U+06ED): الصغيرات العلوية
            // والسفلية، رءوس الأحزاب، سجدة، ومنتهى الآية — علامات نطق لا
            // حروف. يشمل ۞ (U+06DE).
            // نطاق «العربية الممتدة - A» (U+08A0–U+08FF): حركاته الخالصة
            // فقط (U+08D3–U+08E1 و U+08E3–U+08FF) لأن بقية النطاق يحوي
            // حروفاً هجائية للأوردو والبشتو واللغات الأفريقية.
            // أشكال العرض العربية المزخرفة (U+FDF2–U+FDFF): ﷽ وأخواتها —
            // تُحذف لأنها رموز تصويرية تشوّش النطق.
            if (cp in 0x0610..0x061A ||
                cp == 0x0640 ||
                cp == 0x0670 ||
                cp in 0x064B..0x065F ||
                cp in 0x06D6..0x06ED ||
                cp in 0x08D3..0x08E1 ||
                cp in 0x08E3..0x08FF ||
                cp in 0xFDF2..0xFDFF
            ) continue
            // ڪ (U+06AA كاف مائلة) → ك (U+0643) اعتيادية
            if (cp == 0x06AA) {
                sb.append('\u0643')
                continue
            }
            sb.append(ch)
        }
        return sb.toString()
    }
}