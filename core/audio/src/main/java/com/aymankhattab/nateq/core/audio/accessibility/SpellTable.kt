package com.aymankhattab.nateq.core.audio.accessibility

/**
 * أسماء الحروف والأرقام والرموز للتهجئة (ع٤١-ب4.3) — منطقٌ نقيّ.
 * تُنطق كل خانة باسمها: «ألف» لا «أ»، و«صفر» لا «0».
 */
object SpellTable {

    private val ARABIC_LETTERS: Map<Char, String> = mapOf(
        'ا' to "ألف", 'أ' to "ألف", 'إ' to "ألف", 'آ' to "ألف مدّ",
        'ء' to "همزة", 'ئ' to "ياء همزة", 'ؤ' to "واو همزة",
        'ب' to "باء", 'ت' to "تاء", 'ث' to "ثاء", 'ج' to "جيم",
        'ح' to "حاء", 'خ' to "خاء", 'د' to "دال", 'ذ' to "ذال",
        'ر' to "راء", 'ز' to "زاي", 'س' to "سين", 'ش' to "شين",
        'ص' to "صاد", 'ض' to "ضاد", 'ط' to "طاء", 'ظ' to "ظاء",
        'ع' to "عين", 'غ' to "غين", 'ف' to "فاء", 'ق' to "قاف",
        'ك' to "كاف", 'ل' to "لام", 'م' to "ميم", 'ن' to "نون",
        'ه' to "هاء", 'و' to "واو", 'ي' to "ياء",
        'ى' to "ألف مقصورة", 'ة' to "تاء مربوطة"
    )

    private val DIGITS: Map<Char, String> = mapOf(
        '0' to "صفر", '1' to "واحد", '2' to "اثنان", '3' to "ثلاثة",
        '4' to "أربعة", '5' to "خمسة", '6' to "ستة", '7' to "سبعة",
        '8' to "ثمانية", '9' to "تسعة",
        '٠' to "صفر", '١' to "واحد", '٢' to "اثنان", '٣' to "ثلاثة",
        '٤' to "أربعة", '٥' to "خمسة", '٦' to "ستة", '٧' to "سبعة",
        '٨' to "ثمانية", '٩' to "تسعة"
    )

    private val SYMBOLS: Map<Char, String> = mapOf(
        ' ' to "مسافة",
        '-' to "شرطة", '–' to "شرطة", '—' to "شرطة", 'ـ' to "تطويل",
        '_' to "شرطة سفلية",
        '@' to "آت", '#' to "هاش", '&' to "و", '%' to "بالمئة",
        '+' to "زائد", '*' to "نجمة", '/' to "مائلة", '\\' to "مائلة عكسية",
        '.' to "نقطة", ',' to "فاصلة", '،' to "فاصلة",
        ':' to "نقطتان", ';' to "فاصلة منقوطة", '؛' to "فاصلة منقوطة",
        '?' to "علامة استفهام", '؟' to "علامة استفهام",
        '!' to "علامة تعجّب",
        '(' to "قوس", ')' to "قوس", '[' to "قوس مربّع",
        ']' to "قوس مربّع", '{' to "قوس معقوف", '}' to "قوس معقوف",
        '"' to "علامة تنصيص", '\'' to "علامة تنصيص",
        '\t' to "مسافة", '\n' to "سطر جديد"
    )

    /** اسم الخانة المنطوق؛ وإلا الخانة كما هي (حروف لاتينية مثلاً). */
    fun nameOf(char: Char): String =
        ARABIC_LETTERS[char]
            ?: DIGITS[char]
            ?: SYMBOLS[char]
            ?: char.toString()
}
