package com.aymankhattab.nateq.core.audio.engine

/**
 * ميزانية زمنية واحدة للتخليق يشاركها المزوّد (انتظارُ كتابة ملف WAV)
 * وخدمة TTS (انتظارُ اكتمال الطلب كلّه) وحارسُ الإعلانات — مصدرُ حقيقةٍ
 * واحد لا صيغتان متناقضتان.
 *
 * **لماذا كُدِّرت الثوابت:** قبل v104 كانت الخدمة تفرض مهلةً
 * `20s + 4ms/حرف` بينما المزوّد ينتظر `3s + 30ms/حرف` لنصٍّ واحد،
 * فالمهلةُ الخارجية أقصرُ دائماً من الميزانية الداخلية فتُلغى
 * الطلبات الطويلة في منتصفها. ثم اشتُقّ تقسيمٌ لمقاطع 200 حرف
 * فصار مجموعُ ميزانيات المقاطع (8s لكلٍّ منها) أكبرَ بكثير من
 * مهلة الطلب الواحدة، فيُقطع النطق بعد أوّل بضعة مقاطع. وهذه
 * ليست إلا نسخةٌ واحدة من الصنف نفسه: **مهلةٌ خارجية أقصرُ من
 * الميزانية الداخلية تقطع النصّ في منتصفه.**
 *
 * العقدُ الحاكم: **كل مهلةٍ خارجية ≥ ميزانيتها الداخلية**، ويضمنه
 * اختبارُ `SynthesisBudgetTest`، وهو ما يمنع تكرار الانقطاع.
 */
internal object SynthesisBudget {

    /** تكلفةٌ ثابتة لكل وحدة نطق: تبديلُ المحرك + فتحُ/حذفُ ملف WAV. */
    private const val UNIT_OVERHEAD_MS = 2_000L

    /** وحداتُ حمايةٍ فوق المحسوب (خطأُ التقسيم وتيّاراتُ النظام). */
    private const val UNIT_SLACK = 2

    /** حدّ أدنى لطلبٍ واحد مهما قصر نصّه (سلوكٌ تاريخيّ محفوظ). */
    private const val MIN_REQUEST_MS = 20_000L

    /** سقفُ ميزانية وحدةٍ واحدة (حمايةٌ من نصٍّ شاذٍّ بلا نهاية). */
    private const val MAX_UNIT_MS = 5 * 60_000L

    /** سقفُ مهلة الطلب الواحد — لا يُتجاوز مهما طال النص. */
    private const val MAX_REQUEST_MS = 15 * 60_000L

    /**
     * ميزانية تخليق **نصٍّ واحد** بطول [chars] حرفاً: تُنتظر فيها
     * كتابةُ ملف WAV كاملاً من المحرك.
     *
     * عتبةُ 8 ثوانٍ حتى 300 حرف مقصودة: النصُّ يُسلَّم الآن للمركّب
     * طلباً واحداً متّصلاً، فمهلةُ 3 ثوانٍ الموروثة من زمن النصّ
     * القصير كانت تقتل جملةً طبيعيةً على محركٍ بطيء أو باردِ
     * الشبكة، فتُسقط كلماتٍ كاملةً بصمت.
     */
    fun pieceTimeoutMs(chars: Int): Long = when {
        chars <= 10 -> 1_500L
        chars <= 80 -> 3_000L
        chars <= 300 -> 8_000L
        else -> (8_000L + (chars - 300) * 30L)
            .coerceAtMost(MAX_UNIT_MS)
    }

    /**
     * ميزانية **الطلب الواحد** كاملاً: ميزانيةُ تخليق نصّه
     * ([pieceTimeoutMs]) مضافاً إليها تكلفةُ الوحدة الثابتة.
     *
     * بهامشٍ واحدٍ فقط، لا بمجموع المقاطع: لم يعد القارئ يقسّم
     * النصّ، فيُسلَّم كلُّه طلباً واحداً. ويجب ألّا تقلّ هذه القيمة
     * عن ميزانية المزوّد الداخلية أبداً — وإلا أُلغي الطلبُ من
     * الخارج قبل اكتمال الكتابة، وهو الانقطاعُ الجذري المُعالَج.
     */
    fun requestTimeoutMs(totalChars: Int): Long =
        (pieceTimeoutMs(totalChars) + UNIT_OVERHEAD_MS)
            .coerceIn(MIN_REQUEST_MS, MAX_REQUEST_MS)

    /**
     * ميزانية **قائمة وحدات نطق** (إعلانات تُسلَّم وحدةً وحدةً): مجموع
     * ميزانيات وحداتها ([pieceTimeoutMs] لكلٍّ) مضافاً إليها تكلفةُ كل
     * وحدة ([UNIT_OVERHEAD_MS]) وهامشُ وحداتٍ زائدة ([UNIT_SLACK]).
     *
     * يحتاجها حارسُ الإعلانات: حارسٌ بسقفٍ ثابت (سابقاً 120 ثانية)
     * كان يقطع إعلاناً طويلاً بعد وحداته بوقتٍ طويل لأن مجموع
     * ميزانياتها يتجاوزه — الانقطاعُ نفسه في مسارٍ آخر.
     */
    fun unitsTimeoutMs(charCounts: List<Int>): Long {
        val sum = charCounts.sumOf { pieceTimeoutMs(it) + UNIT_OVERHEAD_MS }
        return (sum + UNIT_SLACK * UNIT_OVERHEAD_MS)
            .coerceIn(MIN_REQUEST_MS, MAX_REQUEST_MS)
    }
}